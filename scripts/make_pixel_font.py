fb = FontBuilder(1000, isTTF=True)
names = {c: 'g' + str(ord(c)) for c in PATTERNS}
fb.setupGlyphOrder(['.notdef'] + list(names.values()))
fb.setupCharacterMap({ord(c): name for c, name in names.items()})
glyphs = {}; metrics = {}
for char in [None] + list(PATTERNS):
    pen = TTGlyphPen(None)
    for y, row in enumerate(PATTERNS.get(char, [])):
        for x, value in enumerate(row):
            if value == '1':
                left, bottom = x * 120, (6 - y) * 120
                pen.moveTo((left, bottom)); pen.lineTo((left, bottom + 120))
                pen.lineTo((left + 120, bottom + 120)); pen.lineTo((left + 120, bottom)); pen.closePath()
    name = names.get(char, '.notdef')
    glyphs[name] = pen.glyph(); metrics[name] = (720, 0)
fb.setupGlyf(glyphs); fb.setupHorizontalMetrics(metrics)
fb.setupHorizontalHeader(ascent=880, descent=-120)
fb.setupNameTable(dict(familyName='BZX Pixel', styleName='Regular', uniqueFontIdentifier='BZXPixel1', fullName='BZX Pixel Regular', psName='BZXPixel-Regular'))
fb.setupOS2(sTypoAscender=880, sTypoDescender=-120, usWinAscent=880, usWinDescent=120)
fb.setupPost(); fb.setupMaxp()
