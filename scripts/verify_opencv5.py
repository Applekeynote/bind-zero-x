"""Execute genuine OpenCV 5 and the captured-image HTTP pipeline.

No version patching. Generated fixtures are always labeled SYNTHETIC.
Real inputs may instead be supplied with --capture-directory.
"""
from pathlib import Path
import argparse
import base64
import hashlib
import importlib.metadata
import json
import os
import platform
import secrets
import sys
from datetime import datetime, timezone

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'bind-zero-x' / 'code'))


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def run(output, capture_directory=None):
    import cv2
    import numpy as np
    from fastapi.testclient import TestClient
    from api_research import app
    from capture_archive import verify_capture
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    if cv2.__version__.split('.')[0] != '5':
        raise RuntimeError('GENUINE_OPENCV5_REQUIRED')
    (output / 'opencv-build.txt').write_text(cv2.getBuildInformation(), encoding='utf-8')
    os.environ['BZX_RESEARCH_LOOP_DB'] = str(output / 'sessions.db')
    os.environ['BZX_CAPTURE_ARCHIVE_DIR'] = str(output / 'captures')
    os.environ['BZX_RESEARCH_TOKEN'] = secrets.token_urlsafe(48)
    # Persistent separate local key is generated by the core for restart verification.
    sid = 'CV5-' + secrets.token_hex(6)
    if capture_directory:
        capture_directory = Path(capture_directory)
        model = json.loads((capture_directory / 'config.json').read_text(encoding='utf-8-sig'))
        images = {k: (capture_directory / (k + '.png')).read_bytes()
                  for k in ('frame0', 'frame1', 'upper_mask', 'lower_mask')}
        tier = 'USER_SUPPLIED_CAMERA_BYTES_NOT_INDEPENDENT_PHYSICAL_GT'
    else:
        tier = 'SYNTHETIC_OPENCV5_API_SMOKE_NOT_PHYSICAL_GT'
        rng = np.random.default_rng(49)
        a = cv2.GaussianBlur(rng.integers(0, 255, (320, 480), dtype=np.uint8), (3, 3), 0)
        b = a.copy(); b[20:145, :] = np.roll(a[20:145, :], 7, axis=1)
        upper = np.zeros_like(a); upper[35:125, 35:440] = 255
        lower = np.zeros_like(a); lower[190:285, 35:440] = 255
        arrays = dict(frame0=a, frame1=b, upper_mask=upper, lower_mask=lower)
        images = {k: cv2.imencode('.png', v)[1].tobytes() for k, v in arrays.items()}
        model = dict(observation_id='SYNTHETIC-' + sid,
            calibration=dict(scale_mm_per_px=0.8, plane_id='SYNTHETIC', calibration_id='SYNTHETIC-ONLY', verified=True),
            roi_manifest=dict(operator_verified=True, frame0_sha256=sha(a.tobytes()),
                layers={k: dict(layer_label=k, source_id='SYNTHETIC-' + k, mask_sha256=sha(mask.tobytes()))
                        for k, mask in [('upper', upper), ('lower', lower)]}),
            worlds=['LAYER_ONLY', 'LAYER_AND_ROPE'],
            losses={'REORDER': {'LAYER_ONLY': 0, 'LAYER_AND_ROPE': 6},
                    'REPOSITION_TWINE': {'LAYER_ONLY': 5, 'LAYER_AND_ROPE': 2},
                    'ABSTAIN': {'LAYER_ONLY': 2, 'LAYER_AND_ROPE': 2}},
            view_signatures={'ROPE_PATH': {'LAYER_ONLY': 'rope_still', 'LAYER_AND_ROPE': 'rope_moved'}},
            view_costs={'ROPE_PATH': 0.25})
    model['session_id'] = sid
    body = dict(model, **{k + '_png_b64': base64.b64encode(raw).decode() for k, raw in images.items()})
    headers = {'Authorization': 'Bearer ' + os.environ['BZX_RESEARCH_TOKEN']}
    with TestClient(app) as client:
        health = client.get('/health').json()
        ready = client.get('/ready')
        if ready.status_code != 200:
            raise RuntimeError('OPENCV5_READY_FAILED')
        result = client.post('/api/research/loop/start-captured', json=body, headers=headers)
        if result.status_code != 200:
            raise RuntimeError('CAPTURE_PIPELINE_FAILED:' + str(result.status_code) + ':' + result.text[:250])
        result = result.json()
    receipt = result['initial_capture_receipt_sha256']
    if not verify_capture(os.environ['BZX_CAPTURE_ARCHIVE_DIR'], receipt):
        raise RuntimeError('CAPTURE_ARCHIVE_VERIFICATION_FAILED')
    report = dict(schema='BZX-GENUINE-OPENCV5-EXECUTION-V1',
        executed_utc=datetime.now(timezone.utc).isoformat(),
        input_tier=tier, platform=platform.platform(), python=platform.python_version(),
        opencv_version=cv2.__version__, distribution_version=importlib.metadata.version('opencv-python-headless'),
        build_information_sha256=sha(cv2.getBuildInformation().encode()),
        input_sha256={k: sha(raw) for k, raw in images.items()},
        health=health, ready=ready.json(), receipt_sha256=receipt,
        archive_verified=True, result=result,
        independent_physical_gt_approved=False,
        aws_execution_environment=os.getenv('AWS_EXECUTION_ENV'),
        aws_region=os.getenv('AWS_REGION') or os.getenv('AWS_DEFAULT_REGION'))
    (output / 'execution.json').write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding='utf-8')
    print(json.dumps({k: report[k] for k in ['input_tier', 'opencv_version', 'archive_verified', 'independent_physical_gt_approved']}, ensure_ascii=False))
    print('Report:', output / 'execution.json')
    return report


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--output', required=True)
    parser.add_argument('--capture-directory')
    args = parser.parse_args()
    run(args.output, args.capture_directory)
